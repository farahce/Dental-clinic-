    private void jButton8ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton8ActionPerformed
String appointmentIdInput = appid.getText().trim(); 
String atime = jTextField7.getText().trim();          
java.util.Date adate = jDateChooser1.getDate();       

if (appointmentIdInput.isEmpty() || (atime.isEmpty() && adate == null)) {
    JOptionPane.showMessageDialog(null, "Please fill in all required fields.", "Error", JOptionPane.ERROR_MESSAGE);
    return;
}

int appointmentId;
try {
    appointmentId = Integer.parseInt(appointmentIdInput); 
} catch (NumberFormatException ex) {
    JOptionPane.showMessageDialog(null, "Appointment ID must be a valid integer.", "Error", JOptionPane.ERROR_MESSAGE);
    return;
}

java.sql.Time sqlTime = null;
if (!atime.isEmpty()) {
    try {
        sqlTime = java.sql.Time.valueOf(atime); 
    } catch (IllegalArgumentException ex) {
        JOptionPane.showMessageDialog(null, "Appointment time must be in the format HH:MM:SS.", "Error", JOptionPane.ERROR_MESSAGE);
        return;
    }
}

java.sql.Date sqlDate = null;
if (adate != null) {
    sqlDate = new java.sql.Date(adate.getTime());
}

String url = "jdbc:postgresql://localhost:5432/postgres";
String user = "dentalclinic";
String password = "12345";

String updateAppointmentQuery;
if (sqlTime != null && sqlDate == null) {
    updateAppointmentQuery = "UPDATE public.appointments SET atime = ? WHERE appointment_id = ?";
} else if (sqlDate != null && sqlTime == null) {
    updateAppointmentQuery = "UPDATE public.appointments SET adate = ? WHERE appointment_id = ?";
} else {
    JOptionPane.showMessageDialog(null, "Specify either a new time or a new date, not both.", "Error", JOptionPane.ERROR_MESSAGE);
    return;
}

try (Connection con = DriverManager.getConnection(url, user, password);
     PreparedStatement updateStmt = con.prepareStatement(updateAppointmentQuery)) {

    int paramIndex = 1;
    if (sqlTime != null) {
        updateStmt.setTime(paramIndex++, sqlTime);
    } else if (sqlDate != null) {
        updateStmt.setDate(paramIndex++, sqlDate);
    }
    updateStmt.setInt(paramIndex, appointmentId);

    int rowsUpdated = updateStmt.executeUpdate();

    if (rowsUpdated > 0) {
        JOptionPane.showMessageDialog(null, "Appointment updated successfully.", "Success", JOptionPane.INFORMATION_MESSAGE);
    } else {
        JOptionPane.showMessageDialog(null, "No appointment found for the given Appointment ID.", "Info", JOptionPane.INFORMATION_MESSAGE);
    }

} catch (SQLException ex) {
    ex.printStackTrace();
    JOptionPane.showMessageDialog(null, "Database error: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
} catch (Exception ex) {
    ex.printStackTrace();
    JOptionPane.showMessageDialog(null, "Unexpected error: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
}



    }//GEN-LAST:event_jButton8ActionPerformed

