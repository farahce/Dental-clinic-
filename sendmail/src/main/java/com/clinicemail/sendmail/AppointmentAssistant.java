    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
String pnameInput = pname.getText().trim();  

if (pnameInput.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Please enter a Patient Name to search.", "Error", JOptionPane.ERROR_MESSAGE);
    return;
}

DefaultTableModel model = (DefaultTableModel) jTable2.getModel();
model.setRowCount(0);  

String url = "jdbc:postgresql://localhost:5432/postgres";
String user = "dentalclinic";
String password = "12345";

String sql = "SELECT * FROM public.appointments WHERE pname = ?";  

try (Connection conn = DriverManager.getConnection(url, user, password);
     PreparedStatement stmt = conn.prepareStatement(sql)) {

    stmt.setString(1, pnameInput);  

    try (ResultSet rs = stmt.executeQuery()) {
        boolean found = false;
        while (rs.next()) {  
            int aid = rs.getInt("appointment_id");
            int pid = rs.getInt("pid"); 
            String pname = rs.getString("pname");  
            String ptime = rs.getString("atime");  
            Date adate = rs.getDate("adate");

            String formattedDate = adate != null ? adate.toString() : ""; 

            model.addRow(new Object[]{aid, pid, pname, ptime, formattedDate}); // Adding in the correct order
            found = true;
        }

        if (!found) {
            JOptionPane.showMessageDialog(this, "No appointment found for Patient Name: " + pnameInput, "No Results", JOptionPane.INFORMATION_MESSAGE);
        }
    }
} catch (SQLException ex) {
    ex.printStackTrace();
    JOptionPane.showMessageDialog(this, "Error retrieving data: " + ex.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
}

    }//GEN-LAST:event_jButton5ActionPerformed

